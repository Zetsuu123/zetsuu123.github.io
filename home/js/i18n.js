export function makeT(lang) {
  const D = lang === 'en' ? EN : EL;
  return (key, ...args) => {
    const v = key in D ? D[key] : EN[key];
    if (v === undefined) return key;
    return typeof v === 'function' ? v(...args) : v;
  };
}
